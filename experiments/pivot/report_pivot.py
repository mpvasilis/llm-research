"""Turn output/pivot/analysis.json into LaTeX macros and tables for the paper.

    python -m experiments.pivot.report_pivot                    # writes out/paper/pivot_results.tex
    python -m experiments.pivot.report_pivot --analysis A --out B

Every number in the pivot sections of the paper comes from this file. Without
results, out/paper/pivot_results.tex holds only \\pivotfalse and the paper
builds without those sections.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
NAMES = {"empathy_opener": "empathy", "validation": "validation",
         "disclaimer": "referral/disclaimer", "structure": "structuring"}
SHORT = {"empathy_opener": "empathy", "validation": "validation", "disclaimer": "referral", "structure": "structuring"}
CONTRAST = {("flip_chosen_only", "baseline"): "Flip", ("drop_chosen_only", "random_drop"): "Drop",
            ("length_matched", "baseline"): "Len."}
MACRO = {("flip_chosen_only", "structure"): "FlipStruct", ("flip_chosen_only", "disclaimer"): "FlipDisc",
         ("drop_chosen_only", "structure"): "DropStruct", ("drop_chosen_only", "disclaimer"): "DropDisc"}


def pp(x):
    v = 100 * x
    return f"${v:+.1f}$".replace("+", "{+}") if abs(v) >= 0.05 else "$0.0$"


def pval(p):
    return "$<$.001" if p < 0.001 else f"{p:.3f}".lstrip("0")


def num(v):
    return f"${v:.1f}$"


def ci(c):
    return f"[{num(100 * c[0])}, {num(100 * c[1])}]"


def seeds(row):
    s = row.get("per_training_seed")
    return f"{num(100 * min(s))} to {num(100 * max(s))}" if s else "--"


def render(an):
    cf, at = an["counterfactual"], an["atlas"]
    lines = ["% generated by experiments/pivot/report_pivot.py; do not edit", r"\pivottrue"]
    for row in cf["primary"]:
        key = MACRO[(row["left"], row["category"])]
        lines += [rf"\newcommand{{\piv{key}}}{{{pp(row['estimate'])}}}",
                  rf"\newcommand{{\piv{key}CI}}{{{ci(row['ci95'])}}}",
                  rf"\newcommand{{\piv{key}P}}{{{pval(row['holm_p'])}}}"]
    n_sig = sum(r["holm_p"] < 0.05 for r in cf["primary"])
    lines.append(rf"\newcommand{{\pivNSig}}{{{n_sig}}}")
    only = [r["n_chosen_only"] for runs in an["training"].values() for r in runs if "n_chosen_only" in r]
    pairs = [r["n_train"] for r in an["training"].get("baseline", [])]
    acc = [r["final_acc"] for runs in an["training"].values() for r in runs if r.get("final_acc") is not None]
    lines += [rf"\newcommand{{\pivNChosenOnly}}{{{int(np.mean(only)):,}}}".replace(",", "{,}") if only else r"\newcommand{\pivNChosenOnly}{--}",
              rf"\newcommand{{\pivNPairs}}{{{int(np.mean(pairs)):,}}}".replace(",", "{,}") if pairs else r"\newcommand{\pivNPairs}{--}",
              rf"\newcommand{{\pivFinalAcc}}{{{np.mean(acc):.2f}}}" if acc else r"\newcommand{\pivFinalAcc}{--}"]

    # Table: primary rows, then non-target and length-matched rows from the secondary set
    rows = [(r, True) for r in cf["primary"]]
    for r in cf["secondary"]:
        if r["window"] != 256:
            continue
        nontarget = r["category"] in ("empathy_opener", "validation") and r["left"] != "length_matched"
        target_lm = r["category"] in ("structure", "disclaimer") and r["left"] == "length_matched"
        if nontarget or target_lm:
            rows.append((r, False))
    body = []
    for r, primary in rows:
        body.append(f"{CONTRAST[(r['left'], r['right'])]} & {SHORT[r['category']]}{'' if primary else '$^\\dagger$'} & "
                    f"{pp(r['estimate'])} & {ci(r['ci95'])} & {pval(r['holm_p']) if primary else pval(r['p'])} & {seeds(r)} \\\\")
    lines += [r"\newcommand{\pivPrimaryRows}{%"] + body + ["}"]

    # Atlas: share of the 12 rule-window specifications with a positive gap change
    share = {(s["size"], s["from"], s["to"], s["category"]): s["share_positive"] for s in at["sign_flip"]}
    exact = {(t["size"], t["from"], t["to"], t["category"]): t["gap_change"] for t in at["table"]
             if t["rule"] == "exact" and t["window"] == 256}
    body = []
    for key in sorted(share, key=lambda k: (k[0], ["sft", "dpo", "rlvr"].index(k[1]), k[3])):
        size, a, b, cat = key
        body.append(f"{size} & {a.upper()}$\\to${b.upper()} & {NAMES[cat]} & {pp(exact[key])} & {share[key]:.2f} \\\\")
    lines += [r"\newcommand{\pivAtlasRows}{%"] + body + ["}"]
    flips = sum(0 < v < 1 for v in share.values())
    lines.append(rf"\newcommand{{\pivAtlasMixed}}{{{flips}}}")
    lines.append(rf"\newcommand{{\pivAtlasTotal}}{{{len(share)}}}")
    body = [f"{f['size']} & {f['stage'].upper()} & {NAMES[f['category']]} & {pp(f['chat_minus_qa_gap'])} \\\\"
            for f in at["format_effect"]]
    lines += [r"\newcommand{\pivFormatRows}{%"] + body + ["}"]
    fmt = [abs(f["chat_minus_qa_gap"]) for f in at["format_effect"]]
    lines.append(rf"\newcommand{{\pivFormatMax}}{{{100 * max(fmt):.1f}}}")
    caps = an.get("generation", {})
    cap = [v["cap_share"] for k, v in caps.items() if k.startswith("cf_")]
    lines.append(rf"\newcommand{{\pivCapShare}}{{{100 * np.mean(cap):.1f}}}" if cap else r"\newcommand{\pivCapShare}{--}")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--analysis", type=Path, default=ROOT / "output" / "pivot" / "analysis.json")
    ap.add_argument("--out", type=Path, default=ROOT / "out" / "paper" / "pivot_results.tex")
    a = ap.parse_args()
    a.out.write_text(render(json.loads(a.analysis.read_text(encoding="utf-8"))), encoding="utf-8")
    print("wrote", a.out)


if __name__ == "__main__":
    main()
